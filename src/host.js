// dsh-breeze-tts · 宿主半边
//
// 一个面板，把本地 Breeze TTS 2（breeze-server）整个包起来：
//   · 连接状态 / 一键启停服务
//   · 音色：列出、试听、改描述、删除、从参考音频新建（保存到 Breeze 的 voices 目录）
//   · 生成：音色设计 / 克隆 / 导演 / 变声（实验），结果自动存到固定文件夹
//   · 文件：列表、播放、勾选删除、打开文件夹
//   · 接入 Aurabot：写它的本地接口 tts.mjs + 打开 local.tts 开关（可还原）
//
// 只依赖 Node 自带能力（fetch / FormData / Blob / child_process），不需要额外依赖。
// 面板接口统一在 /breeze-tts/api/*（网页半边见 client/client.js）。

