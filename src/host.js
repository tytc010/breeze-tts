function readJson(file, fallback) {
  try {
    let t = readFileSync(file, 'utf8')
    if (t.charCodeAt(0) === 0xfeff) t = t.slice(1)
    return JSON.parse(t)
  } catch (error) {
    return typeof fallback === 'function' ? fallback() : fallback
  }
}

function writeJson(file, value) {
  mkdirSync(dirname(file), { recursive: true })
  const tmp = `${file}.tmp-${process.pid}`
  writeFileSync(tmp, JSON.stringify(value, null, 2), 'utf8')
  renameSync(tmp, file)
}

/** 16 位小端单声道 PCM → 44 字节头的 WAV。 */
function pcmToWav(pcm, rate = 24000) {
  const header = Buffer.alloc(44)
  header.write('RIFF', 0, 'ascii')
  header.writeUInt32LE(36 + pcm.length, 4)
  header.write('WAVE', 8, 'ascii')
  header.write('fmt ', 12, 'ascii')
  header.writeUInt32LE(16, 16)
  header.writeUInt16LE(1, 20)
  header.writeUInt16LE(1, 22)
  header.writeUInt32LE(rate, 24)
  header.writeUInt32LE(rate * 2, 28)
  header.writeUInt16LE(2, 32)
  header.writeUInt16LE(16, 34)
  header.write('data', 36, 'ascii')
  header.writeUInt32LE(pcm.length, 40)
  return Buffer.concat([header, pcm])
}

function isWav(buf) {
  return buf.length > 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WAVE'
}

export function apply(ctx) {
  // ---------- 配置 ----------
  let cfg = { ...DEFAULTS, ...readJson(CONFIG_FILE(), {}) }
  cfg.aurabot = { ...DEFAULTS.aurabot, ...(cfg.aurabot || {}) }
  const outDir = () => {
    const d = cfg.outDir || join(homedir(), 'BreezeTTS-voice')
    mkdirSync(d, { recursive: true })
    return d
  }
  const saveCfg = (patch) => {
    cfg = { ...cfg, ...patch, aurabot: { ...cfg.aurabot, ...(patch.aurabot || {}) } }
    writeJson(CONFIG_FILE(), cfg)
    return cfg
  }

  // ---------- 服务进程 ----------
  let proc = null
  let logRing = []
  const pushLog = (line) => {
    for (const l of String(line).split(/\r?\n/)) {
      if (!l.trim()) continue
      logRing.push({ at: Date.now(), line: l.slice(0, 400) })
    }
    if (logRing.length > 300) logRing = logRing.slice(-300)
  }

  const base = () => String(cfg.endpoint || DEFAULTS.endpoint).replace(/\/+$/, '')

  function startServer() {
    if (proc && !proc.killed) return { ok: true, message: '服务已经在跑了' }
    const exe = cfg.exePath
    const model = cfg.modelPath
    if (!existsSync(exe)) return { ok: false, message: `找不到 breeze-server.exe：${exe}` }
    if (!existsSync(model)) return { ok: false, message: `找不到模型文件：${model}` }
    try {
      proc = spawn(exe, [model, '--host', '127.0.0.1', '--port', String(cfg.port || 8080)], {
        cwd: dirname(exe),
        windowsHide: true,
        stdio: ['ignore', 'pipe', 'pipe'],
      })
    } catch (error) {
      proc = null
      return { ok: false, message: '启动失败：' + error.message }
    }
    proc.stdout.on('data', (d) => pushLog(d.toString()))
    proc.stderr.on('data', (d) => pushLog(d.toString()))
    proc.on('exit', (code) => {
      pushLog(`[退出] 进程结束，code=${code}`)
      proc = null
    })
    proc.on('error', (e) => pushLog('[错误] ' + e.message))
    return { ok: true, message: '正在启动，模型加载约 20 秒' }
  }

  function stopServer() {
    if (!proc) return { ok: true, message: '服务没在跑' }
    const pid = proc.pid
    try {
      if (process.platform === 'win32') spawn('taskkill', ['/pid', String(pid), '/T', '/F'], { windowsHide: true })
      else proc.kill('SIGTERM')
    } catch (error) {}
    proc = null
    return { ok: true, message: '已停止' }
  }

  async function ping(timeoutMs = 1500) {
    const t = Date.now()
    try {
      const r = await fetch(base() + '/health', { signal: AbortSignal.timeout(timeoutMs) })
      if (!r.ok) return { online: false, ms: Date.now() - t, message: `HTTP ${r.status}` }
      let info = null
      try { info = await r.json() } catch (error) {}
      return { online: true, ms: Date.now() - t, info }
    } catch (error) {
      return { online: false, ms: Date.now() - t, message: String(error.message || error).slice(0, 160) }
    }
  }

  // ---------- 调 Breeze ----------
  // 统一走原生 multipart 接口（能带参考音频），响应是裸 PCM，这里包成 WAV。
  async function breezeSpeech({ fields, file, timeoutMs = 180000 }) {
    const fd = new FormData()
    for (const [k, v] of Object.entries(fields || {})) {
      if (v === undefined || v === null || v === '') continue
      fd.append(k, String(v))
    }
    if (file) fd.append(file.field, new Blob([file.buffer], { type: file.type || 'audio/wav' }), file.name || 'ref.wav')
    const r = await fetch(base() + '/v1/audio/speech', { method: 'POST', body: fd, signal: AbortSignal.timeout(timeoutMs) })
    if (!r.ok) {
      let msg = `HTTP ${r.status}`
      try { msg += '：' + (await r.text()).slice(0, 200) } catch (error) {}
      throw new Error(msg)
    }
    const rate = Number(r.headers.get('x-sample-rate') || 24000)
    const buf = Buffer.from(await r.arrayBuffer())
    if (!buf.length) throw new Error('服务没返回音频')
    return { buffer: isWav(buf) ? buf : pcmToWav(buf, rate), rate }
  }

  async function breezeJson(path, init) {
    const r = await fetch(base() + path, { ...init, signal: AbortSignal.timeout(30000) })
    const text = await r.text()
    if (!r.ok) throw new Error(`HTTP ${r.status}：${text.slice(0, 200)}`)
    try { return JSON.parse(text) } catch (error) { return text }
  }

  // ---------- 生成队列（Breeze 单并发，这里串起来） ----------
  let chain = Promise.resolve()
  let waiting = 0
  const withLock = (fn) => {
    waiting += 1
    const run = chain.then(fn, fn)
    chain = run.then(() => {}, () => {}).finally(() => { waiting -= 1 })
    return run
  }

  const stamp = () => new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
  const safeSlug = (s, max = 24) => String(s || '').replace(/[\\/:*?"<>|\r\n\t]+/g, '').trim().slice(0, max)

  function saveAudio(buf, prefix) {
    const dir = outDir()
    const file = join(dir, `${prefix}-${stamp()}.wav`)
    writeFileSync(file, buf)
    return { file, name: basename(file) }
  }

  function listFiles() {
    const dir = outDir()
    let names = []
    try { names = readdirSync(dir) } catch (error) { return [] }
    const out = []
    for (const n of names) {
      if (!/\.(wav|mp3|ogg|flac)$/i.test(n)) continue
      try {
        const st = statSync(join(dir, n))
        if (!st.isFile()) continue
        out.push({ name: n, size: st.size, mtime: st.mtimeMs })
      } catch (error) {}
    }
    out.sort((a, b) => b.mtime - a.mtime)
    return out.slice(0, 500)
  }

  function filePathOf(name) {
    const n = basename(String(name || ''))
    if (!n || n !== String(name) || n.includes('..')) throw new Error('文件名不合法')
    const full = resolve(outDir(), n)
    if (!full.startsWith(resolve(outDir()))) throw new Error('文件名不合法')
    return full
  }

  // ---------- 面板接口小工具 ----------
  const send = (res, code, body, type = 'application/json; charset=utf-8') => {
    try {
      res.statusCode = code
      res.setHeader?.('content-type', type)
      res.setHeader?.('cache-control', 'no-store')
      res.end?.(typeof body === 'string' || Buffer.isBuffer(body) ? body : JSON.stringify(body))
    } catch (error) {}
  }
  const readRaw = async (req, max) => {
    const parts = []
    let n = 0
    for await (const c of req) {
      const b = Buffer.isBuffer(c) ? c : Buffer.from(c)
      n += b.length
      if (n > max) throw new Error(`请求太大（上限 ${Math.round(max / 1024 / 1024)}MB）`)
      parts.push(b)
    }
    return Buffer.concat(parts)
  }
  const readBody = async (req) => {
    try { return JSON.parse((await readRaw(req, 64 * 1024 * 1024)).toString('utf8') || '{}') } catch (error) { return {} }
  }
  const query = (req) => {
    try { return Object.fromEntries(new URL(req.url, 'http://x').searchParams) } catch (error) { return {} }
  }
  /** 当前 DSH 网页服务的地址（从请求头拿），用来回调 Aurabot 的接口。 */
  const hostBaseOf = (req) => {
    try { const h = req?.headers?.host || ''; return h ? 'http://' + h : '' } catch (error) { return '' }
  }
  const ok = (v) => (v && typeof v === 'object' ? { ok: true, ...v } : { ok: true, value: v })
  const route = (path, handler) => ctx.effect(
    () => ctx.webServer.register({ kind: 'exact', path: PREFIX + path, handler }),
    `breeze-tts: 路由 ${path}`,
  )
  const json = (path, handler) => route(path, async (req, res) => {
    try {
      const r = await handler(req, res)
      if (r !== undefined && !res.writableEnded) send(res, 200, r)
    } catch (error) {
      if (!res.writableEnded) send(res, 200, { ok: false, message: String(error.message || error) })
    }
  })

  // ---------- Aurabot 接入 ----------
  const aurabotDir = () => join(dshHome(), 'plugins-data', 'aurabot')
  const aurabotTts = () => join(aurabotDir(), 'local', 'tts.mjs')
  const aurabotCfg = () => join(aurabotDir(), 'config.json')
  const aurabotVoice = () => dataDir('aurabot-voice.json')

  const AURABOT_SCRIPT = `${MARKER}（由 Breeze TTS 面板生成，删掉这个文件即可恢复）
// 让大肥鱼的语音条走本地 Breeze TTS 2。参数由面板写进 aurabot-voice.json，这里只负责调用。
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const CONF = ${JSON.stringify(dataDir('aurabot-voice.json')).replace(/\\/g, '\\\\')}

function load() {
  try { return JSON.parse(readFileSync(CONF, 'utf8')) } catch (e) { return {} }
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

export default async function tts({ text, outDir, log }) {
  const c = load()
  const endpoint = String(c.endpoint || 'http://127.0.0.1:8080').replace(/\\/+$/, '')
  const dir = c.outDir || outDir
  mkdirSync(dir, { recursive: true })
  const noRetry = new Set(['400', '404'])
  let last = ''
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const fd = new FormData()
      fd.append('text', text)
      if (c.voiceId) fd.append('voice_id', c.voiceId)
      if (c.instruction) fd.append('instruction', c.instruction)
      if (c.cfgScale) fd.append('cfg_scale', String(c.cfgScale))
      const r = await fetch(endpoint + '/v1/audio/speech', { method: 'POST', body: fd, signal: AbortSignal.timeout(55000) })
      if (!r.ok) {
        last = 'HTTP ' + r.status
        if (r.status === 409) { await sleep(700 * (attempt + 1)); continue }
        throw new Error(last)
      }
      const rate = Number(r.headers.get('x-sample-rate') || 24000)
      const pcm = Buffer.from(await r.arrayBuffer())
      if (!pcm.length) throw new Error('没拿到音频')
      if (pcm.toString('ascii', 0, 4) === 'RIFF') {
        const f = join(dir, 'qq-' + Date.now() + '.wav')
        writeFileSync(f, pcm)
        return f
      }
      const h = Buffer.alloc(44)
      h.write('RIFF', 0, 'ascii'); h.writeUInt32LE(36 + pcm.length, 4); h.write('WAVE', 8, 'ascii')
      h.write('fmt ', 12, 'ascii'); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22)
      h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34)
      h.write('data', 36, 'ascii'); h.writeUInt32LE(pcm.length, 40)
      const f = join(dir, 'qq-' + Date.now() + '.wav')
      writeFileSync(f, Buffer.concat([h, pcm]))
      log?.info?.('Breeze 念好了：' + String(text).slice(0, 20))
      return f
    } catch (e) {
      last = String(e.message || e)
      if (attempt === 3) break
      await sleep(500 * (attempt + 1))
    }
  }
  throw new Error('Breeze TTS 失败：' + last)
}
`

  function aurabotStatus() {
    const file = aurabotTts()
    const hasScript = existsSync(file)
    const mine = hasScript && readFileSync(file, 'utf8').includes(MARKER)
    const conf = readJson(aurabotCfg(), {}) || {}
    return {
      ok: true,
      dir: aurabotDir(),
      script: file,
      scriptExists: hasScript,
      managed: mine,
      enabled: Boolean(conf.local && conf.local.tts),
      backup: existsSync(file + '.bak'),
      voice: readJson(aurabotVoice(), {}),
    }
  }

  // Aurabot 把配置读进内存，直接改它的 config.json 不会立刻生效：
  // 这里再走一次它的 /save，让它重新加载（失败不影响文件已写入）。
  async function notifyAurabot(hostBase, localCfg) {
    if (!hostBase) return false
    try {
      const r = await fetch(hostBase + '/aurabot/api/save', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ local: localCfg }),
        signal: AbortSignal.timeout(8000),
      })
      return r.ok
    } catch (error) {
      return false
    }
  }

  async function aurabotEnable(hostBase) {
    mkdirSync(join(aurabotDir(), 'local'), { recursive: true })
    const file = aurabotTts()
    if (existsSync(file)) {
      const cur = readFileSync(file, 'utf8')
      if (!cur.includes(MARKER)) copyFileSync(file, file + '.bak')
    }
    writeFileSync(file, AURABOT_SCRIPT, 'utf8')
    writeJson(aurabotVoice(), {
      endpoint: base(),
      outDir: outDir(),
      voiceId: cfg.aurabot.voiceId || cfg.defaultVoice || '',
      instruction: cfg.aurabot.instruction || cfg.instruction || '',
      cfgScale: Number(cfg.aurabot.cfgScale || 1),
    })
    const conf = readJson(aurabotCfg(), {}) || {}
    conf.local = { ...(conf.local || {}), tts: true }
    writeJson(aurabotCfg(), conf)
    saveCfg({ aurabot: { ...cfg.aurabot, enabled: true } })
    const reloaded = await notifyAurabot(hostBase, conf.local)
    return {
      ok: true,
      reloaded,
      message: reloaded
        ? '已接入，Aurabot 已重新加载配置，立刻生效'
        : '文件已写入；如果 Aurabot 正在运行，请在它的面板点一次「保存设置」让它重新加载',
    }
  }

  async function aurabotDisable(hostBase) {
    const file = aurabotTts()
    try {
      if (existsSync(file + '.bak')) { copyFileSync(file + '.bak', file); unlinkSync(file + '.bak') }
      else if (existsSync(file)) unlinkSync(file)
    } catch (error) {}
    const conf = readJson(aurabotCfg(), {}) || {}
    conf.local = { ...(conf.local || {}), tts: false }
    writeJson(aurabotCfg(), conf)
    saveCfg({ aurabot: { ...cfg.aurabot, enabled: false } })
    const reloaded = await notifyAurabot(hostBase, conf.local)
    return { ok: true, reloaded, message: reloaded ? '已断开，Aurabot 已重新加载配置' : '已断开（Aurabot 若在运行，需在它面板保存一次设置才完全生效）' }
  }

  // ---------- 路由 ----------
  json('/state', async () => ({
    ok: true,
    config: cfg,
    health: await ping(),
    server: { running: Boolean(proc), pid: proc?.pid || 0, logs: logRing.slice(-40) },
    queue: waiting,
    outDir: outDir(),
    files: listFiles().slice(0, 20),
    aurabot: aurabotStatus(),
  }))

  json('/config', async (req) => {
    const b = await readBody(req)
    const patch = {}
    for (const k of ['endpoint', 'port', 'exePath', 'modelPath', 'outDir', 'autoStart', 'defaultVoice', 'instruction', 'cfgScale', 'seed']) {
      if (b[k] !== undefined) patch[k] = b[k]
    }
    if (b.aurabot && typeof b.aurabot === 'object') patch.aurabot = b.aurabot
    return { ok: true, config: saveCfg(patch) }
  })

  json('/health', async () => ({ ok: true, health: await ping() }))

  json('/server/start', async () => startServer())
  json('/server/stop', async () => stopServer())
  json('/logs', async () => ({ ok: true, logs: logRing.slice(-200) }))

  json('/voices', async () => {
    try {
      const list = await breezeJson('/v1/voices')
      return { ok: true, list: Array.isArray(list) ? list : [], presets: cfg.presets || [] }
    } catch (error) {
      return { ok: false, message: String(error.message || error), list: [], presets: cfg.presets || [] }
    }
  })

  // 新建音色：上传参考音频 + 逐字稿 → 保存到 Breeze 的 voices 目录
  json('/voices/save', async (req) => {
    const b = await readBody(req)
    const name = String(b.name || '').trim()
    if (!/^[A-Za-z0-9_-]{1,64}$/.test(name)) throw new Error('音色名只能用字母、数字、- 和 _，最多 64 个字符')
    if (!b.refText) throw new Error('必须填参考音频的逐字稿')
    if (!b.audio) throw new Error('没有上传参考音频')
    const fd = new FormData()
    fd.append('ref_audio', new Blob([Buffer.from(String(b.audio), 'base64')], { type: b.mime || 'audio/wav' }), b.filename || 'ref.wav')
    fd.append('ref_text', String(b.refText))
    fd.append('name', name)
    if (b.description) fd.append('description', String(b.description))
    if (b.metadata && typeof b.metadata === 'object') fd.append('metadata', JSON.stringify(b.metadata))
    const r = await fetch(base() + '/v1/voices', { method: 'POST', body: fd, signal: AbortSignal.timeout(120000) })
    const text = await r.text()
    if (!r.ok) throw new Error(`保存失败（HTTP ${r.status}）：${text.slice(0, 200)}`)
    return { ok: true, voice: (() => { try { return JSON.parse(text) } catch (e) { return text } })() }
  })

  json('/voices/patch', async (req) => {
    const b = await readBody(req)
    const id = String(b.id || '')
    if (!id) throw new Error('缺少音色 id')
    const body = {}
    if (b.description !== undefined) body.description = b.description
    if (b.metadata !== undefined) body.metadata = b.metadata
    const r = await fetch(base() + '/v1/voices/' + encodeURIComponent(id), {
      method: 'PATCH',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(30000),
    })
    const text = await r.text()
    if (!r.ok) throw new Error(`改描述失败（HTTP ${r.status}）：${text.slice(0, 200)}`)
    return { ok: true, voice: (() => { try { return JSON.parse(text) } catch (e) { return text } })() }
  })

  json('/voices/delete', async (req) => {
    const b = await readBody(req)
    const id = String(b.id || '')
    if (!id) throw new Error('缺少音色 id')
    const r = await fetch(base() + '/v1/voices/' + encodeURIComponent(id), { method: 'DELETE', signal: AbortSignal.timeout(20000) })
    const text = await r.text()
    if (!r.ok) throw new Error(`删除失败（HTTP ${r.status}）：${text.slice(0, 200)}`)
    return { ok: true, result: (() => { try { return JSON.parse(text) } catch (e) { return text } })(), message: '已从内存移除；磁盘上的 .breeze 文件仍在（重启后会回来）' }
  })

  json('/presets/save', async (req) => {
    const b = await readBody(req)
    const name = String(b.name || '').trim() || `设计-${(cfg.presets || []).length + 1}`
    const instruction = String(b.instruction || '').trim()
    if (!instruction) throw new Error('描述不能为空')
    const list = (cfg.presets || []).filter((p) => p.name !== name)
    list.push({ name, instruction })
    saveCfg({ presets: list })
    return { ok: true, presets: list }
  })

  json('/presets/delete', async (req) => {
    const b = await readBody(req)
    const list = (cfg.presets || []).filter((p) => p.name !== String(b.name || ''))
    saveCfg({ presets: list })
    return { ok: true, presets: list }
  })

  // 生成：mode = design | clone | direction
  json('/speak', async (req) => {
    const b = await readBody(req)
    const text = String(b.text || '').trim()
    if (!text) throw new Error('没有要念的文字')
    const mode = ['design', 'clone', 'direction'].includes(b.mode) ? b.mode : 'design'
    const fields = {
      text,
      instruction: b.instruction || cfg.instruction,
      cfg_scale: b.cfgScale ?? cfg.cfgScale,
      seed: b.seed ?? cfg.seed,
    }
    let file = null
    if (mode === 'design') {
      // 设计：不给 voice_id，靠 instruction
    } else if (b.audio) {
      fields.ref_text = b.refText || ''
      if (!fields.ref_text) throw new Error('上传参考音频时必须填它的逐字稿')
      file = { field: 'ref_audio', buffer: Buffer.from(String(b.audio), 'base64'), name: b.filename || 'ref.wav', type: b.mime || 'audio/wav' }
      if (mode === 'clone' && b.instruction) fields.instruction = b.instruction
    } else {
      if (!b.voiceId) throw new Error('克隆/导演要选一个音色，或者上传参考音频')
      fields.voice_id = b.voiceId
    }
    const t = Date.now()
    const { buffer } = await withLock(() => breezeSpeech({ fields, file }))
    const saved = saveAudio(buffer, `${mode}-${safeSlug(b.voiceId || b.presetName || 'voice', 18)}`)
    return {
      ok: true,
      file: saved.name,
      path: saved.file,
      seconds: Math.max(0, (buffer.length - 44) / 2 / 24000),
      ms: Date.now() - t,
      mode,
    }
  })

  // 变声（实验）：把一段录音换成另一个音色
  json('/convert', async (req) => {
    const b = await readBody(req)
    if (!b.audio) throw new Error('没有上传源录音')
    const fd = new FormData()
    fd.append('source', new Blob([Buffer.from(String(b.audio), 'base64')], { type: b.mime || 'audio/wav' }), b.filename || 'source.wav')
    if (b.voiceId) fd.append('voice_id', String(b.voiceId))
    if (b.refText) fd.append('ref_text', String(b.refText))
    if (b.text) fd.append('text', String(b.text))
    if (b.keepAcoustic) fd.append('keep_acoustic', String(b.keepAcoustic))
    if (b.temperature) fd.append('temperature', String(b.temperature))
    const r = await withLock(() => fetch(base() + '/v1/audio/convert', { method: 'POST', body: fd, signal: AbortSignal.timeout(300000) }))
    if (!r.ok) throw new Error(`变声失败（HTTP ${r.status}）：${(await r.text()).slice(0, 200)}`)
    const buf = Buffer.from(await r.arrayBuffer())
    const saved = saveAudio(isWav(buf) ? buf : pcmToWav(buf, 24000), 'convert')
    return { ok: true, file: saved.name, path: saved.file, ms: 0 }
  })

  json('/files', async () => ({ ok: true, dir: outDir(), files: listFiles() }))

  json('/files/delete', async (req) => {
    const b = await readBody(req)
    const names = Array.isArray(b.names) ? b.names : []
    let n = 0
    for (const name of names) {
      try { unlinkSync(filePathOf(name)); n += 1 } catch (error) {}
    }
    return { ok: true, deleted: n, files: listFiles() }
  })

  json('/files/open', async () => {
    const dir = outDir()
    try {
      if (process.platform === 'win32') spawn('explorer.exe', [dir], { detached: true, stdio: 'ignore' }).unref()
      else if (process.platform === 'darwin') spawn('open', [dir], { detached: true, stdio: 'ignore' }).unref()
      else spawn('xdg-open', [dir], { detached: true, stdio: 'ignore' }).unref()
      return { ok: true, dir }
    } catch (error) {
      return { ok: false, message: '打不开文件夹：' + error.message }
    }
  })

  // 播放：直接把文件流出去
  route('/file', async (req, res) => {
    try {
      const full = filePathOf(query(req).name)
      if (!existsSync(full)) return send(res, 404, { ok: false, message: '文件不存在' })
      const ext = extname(full).toLowerCase()
      const type = ext === '.mp3' ? 'audio/mpeg' : ext === '.ogg' ? 'audio/ogg' : 'audio/wav'
      res.statusCode = 200
      res.setHeader?.('content-type', type)
      res.setHeader?.('cache-control', 'no-store')
      res.setHeader?.('accept-ranges', 'none')
      createReadStream(full).pipe(res)
    } catch (error) {
      send(res, 400, { ok: false, message: String(error.message || error) })
    }
  })

  json('/aurabot', async () => aurabotStatus())
  json('/aurabot/enable', async (req) => {
    const b = await readBody(req)
    if (b.voiceId !== undefined || b.instruction !== undefined || b.cfgScale !== undefined) {
      saveCfg({ aurabot: { ...cfg.aurabot, voiceId: b.voiceId ?? cfg.aurabot.voiceId, instruction: b.instruction ?? cfg.aurabot.instruction, cfgScale: b.cfgScale ?? cfg.aurabot.cfgScale } })
    }
    return aurabotEnable(hostBaseOf(req))
  })
  json('/aurabot/disable', async (req) => aurabotDisable(hostBaseOf(req)))
  json('/aurabot/test', async () => {
    const t = Date.now()
    const { buffer } = await withLock(() => breezeSpeech({ fields: { text: '你好呀，我是大肥鱼。', voice_id: cfg.aurabot.voiceId || cfg.defaultVoice, instruction: cfg.aurabot.instruction, cfg_scale: cfg.aurabot.cfgScale } }))
    const saved = saveAudio(buffer, 'aurabot-test')
    return { ok: true, file: saved.name, ms: Date.now() - t, seconds: (buffer.length - 44) / 2 / 24000 }
  })

  // 开机自启（插件加载时如果开着就尝试拉起）
  if (cfg.autoStart) {
    setTimeout(() => {
      if (!proc) {
        const h = startServer()
        pushLog('[自启] ' + h.message)
      }
    }, 3000)
  }

  return { startServer, stopServer, ping }
}
